'use strict';

const path = require('path');
const fs = require('fs');
const { loadRepoData } = require('./validate-data');

const PROJECT_ROOT = path.join(__dirname, '..');
const REPORT_PATH = path.join(PROJECT_ROOT, 'docs', 'sparse-tier-inventory.md');

const SEVERITY_ORDER = { HIGH: 0, MEDIUM: 1, INFO: 2, POSSIBLE_GAP: 3 };

function auditSparseTiers(categories) {
  const groupMap = new Map();

  for (const cat of categories) {
    const catName = cat.category;
    for (const pair of cat.pairs) {
      const key = `${catName}||${pair.group}`;
      if (!groupMap.has(key)) {
        groupMap.set(key, {
          categoryName: catName,
          groupId: pair.group,
          label: `${pair.contrastPhoneme1}/${pair.contrastPhoneme2}`,
          tierPairs: new Map(),
        });
      }
      const entry = groupMap.get(key);
      if (!entry.tierPairs.has(pair.difficulty)) {
        entry.tierPairs.set(pair.difficulty, []);
      }
      entry.tierPairs.get(pair.difficulty).push(pair);
    }
  }

  const sortedGroups = [...groupMap.values()].sort((a, b) => {
    const catCmp = a.categoryName.localeCompare(b.categoryName);
    return catCmp !== 0 ? catCmp : a.groupId.localeCompare(b.groupId);
  });

  let totalGroupTierCombos = 0;
  let healthyCount = 0;
  const sparseTierRows = [];
  const possibleGapRows = [];

  for (const group of sortedGroups) {
    const tiers = [...group.tierPairs.keys()].sort((a, b) => a - b);
    if (tiers.length === 0) continue;
    const minTier = tiers[0];
    const maxTier = tiers[tiers.length - 1];

    totalGroupTierCombos += tiers.length;

    for (const tier of tiers) {
      const pairs = [...group.tierPairs.get(tier)].sort(
        (a, b) => a.word1.localeCompare(b.word1) || a.word2.localeCompare(b.word2)
      );

      if (pairs.length >= 2) {
        healthyCount++;
      } else {
        sparseTierRows.push({
          categoryName: group.categoryName,
          groupId: group.groupId,
          label: group.label,
          tier,
          pairCount: pairs.length,
          pairs: pairs.map(p => `${p.word1}/${p.word2}`),
          severity: tier <= 3 ? 'HIGH' : 'MEDIUM',
        });
      }
    }

    for (let tier = minTier + 1; tier < maxTier; tier++) {
      if (!group.tierPairs.has(tier)) {
        possibleGapRows.push({
          categoryName: group.categoryName,
          groupId: group.groupId,
          label: group.label,
          missingTier: tier,
          existingTierRange: `${minTier}–${maxTier}`,
          severity: 'POSSIBLE_GAP',
          note: 'Absent intermediate tier; also flagged by validate-data GROUP_TIER_PRESENT.',
        });
      }
    }
  }

  sparseTierRows.sort((a, b) => {
    const sevCmp = SEVERITY_ORDER[a.severity] - SEVERITY_ORDER[b.severity];
    if (sevCmp !== 0) return sevCmp;
    const catCmp = a.categoryName.localeCompare(b.categoryName);
    if (catCmp !== 0) return catCmp;
    const grpCmp = a.groupId.localeCompare(b.groupId);
    if (grpCmp !== 0) return grpCmp;
    return a.tier - b.tier;
  });

  possibleGapRows.sort((a, b) => {
    const catCmp = a.categoryName.localeCompare(b.categoryName);
    if (catCmp !== 0) return catCmp;
    const grpCmp = a.groupId.localeCompare(b.groupId);
    if (grpCmp !== 0) return grpCmp;
    return a.missingTier - b.missingTier;
  });

  const expansionMap = new Map();
  for (const row of sparseTierRows) {
    const key = `${row.categoryName}||${row.groupId}`;
    if (!expansionMap.has(key)) {
      expansionMap.set(key, {
        categoryName: row.categoryName,
        groupId: row.groupId,
        label: row.label,
        highCount: 0,
        mediumCount: 0,
        sparseTiers: [],
      });
    }
    const entry = expansionMap.get(key);
    if (row.severity === 'HIGH') entry.highCount++;
    else if (row.severity === 'MEDIUM') entry.mediumCount++;
    entry.sparseTiers.push(row.tier);
  }

  const expansionCandidates = [...expansionMap.values()].sort((a, b) => {
    const highCmp = b.highCount - a.highCount;
    if (highCmp !== 0) return highCmp;
    const medCmp = b.mediumCount - a.mediumCount;
    if (medCmp !== 0) return medCmp;
    const catCmp = a.categoryName.localeCompare(b.categoryName);
    if (catCmp !== 0) return catCmp;
    return a.groupId.localeCompare(b.groupId);
  });

  return {
    totalGroups: sortedGroups.length,
    totalGroupTierCombos,
    healthyCount,
    sparseTierCount: sparseTierRows.length,
    possibleGapCount: possibleGapRows.length,
    sparseTierRows,
    possibleGapRows,
    expansionCandidates,
  };
}

function generateMarkdownReport(result) {
  const lines = [];

  lines.push('# Sparse Tier Inventory');
  lines.push('');
  lines.push('> Generated by `node scripts/audit-sparse-tiers.js --write`. Do not edit manually.');
  lines.push('> Re-run after any data change to keep findings current.');
  lines.push('');

  // ── Section 1: Summary counts ─────────────────────────────────────────────
  lines.push('## 1. Summary');
  lines.push('');
  lines.push('| Metric | Count |');
  lines.push('|---|---:|');
  lines.push(`| Total contrast groups (category × group) | ${result.totalGroups} |`);
  lines.push(`| Total group/tier combinations present | ${result.totalGroupTierCombos} |`);
  lines.push(`| Healthy (≥ 2 pairs) | ${result.healthyCount} |`);
  lines.push(`| Single-pair tiers (HIGH + MEDIUM) | ${result.sparseTierCount} |`);
  lines.push(`| Possible missing-tier gaps | ${result.possibleGapCount} |`);
  lines.push('');
  lines.push(
    `**${result.sparseTierCount} of ${result.totalGroupTierCombos} group/tier slots (` +
    `${result.totalGroupTierCombos > 0 ? Math.round((result.sparseTierCount / result.totalGroupTierCombos) * 100) : 0}%) ` +
    `contain exactly one pair and cannot provide rotation variety at that tier.**`
  );
  lines.push('');
  lines.push(
    'This is a dataset coverage limitation, not a scheduler bug. ' +
    'The scheduler handles single-pair tiers correctly; ' +
    'expanding the dataset is the only way to improve variety.'
  );
  lines.push('');

  // ── Section 2: Sparse tier table ─────────────────────────────────────────
  lines.push('## 2. Sparse Tier Table');
  lines.push('');
  lines.push('Showing all group/tier combinations with exactly 1 pair.');
  lines.push('Sorted by: severity → category → group → tier.');
  lines.push('');
  lines.push('| Category | Group ID | Contrast | Tier | Pairs | Severity |');
  lines.push('|---|---|---|---:|---|---|');

  for (const row of result.sparseTierRows) {
    const pairsCell = row.pairs.join(', ');
    lines.push(
      `| ${row.categoryName} | ${row.groupId} | ${row.label} | ${row.tier} | ${pairsCell} | ${row.severity} |`
    );
  }
  lines.push('');

  // ── Section 3: Possible gap table ────────────────────────────────────────
  lines.push('## 3. Possible Tier Gaps');
  lines.push('');
  if (result.possibleGapRows.length === 0) {
    lines.push(
      'No possible gaps detected. `validate-data.js` enforces all tiers 1–6 in every group, ' +
      'so intermediate gaps are already caught as validation errors before reaching this audit.'
    );
  } else {
    lines.push('| Category | Group ID | Contrast | Missing tier | Existing range | Severity | Note |');
    lines.push('|---|---|---|---:|---|---|---|');
    for (const row of result.possibleGapRows) {
      lines.push(
        `| ${row.categoryName} | ${row.groupId} | ${row.label} | ${row.missingTier} | ${row.existingTierRange} | ${row.severity} | ${row.note} |`
      );
    }
  }
  lines.push('');

  // ── Section 4: Prioritized expansion candidates ───────────────────────────
  lines.push('## 4. Prioritized Expansion Candidates');
  lines.push('');
  lines.push('Sorted by: HIGH sparse tiers desc → MEDIUM sparse tiers desc → category → group.');
  lines.push('');
  lines.push('| Priority | Category | Group ID | Contrast | Sparse tiers | HIGH | MEDIUM | Suggested action |');
  lines.push('|---:|---|---|---|---|---:|---:|---|');

  result.expansionCandidates.forEach((c, i) => {
    const tiers = [...c.sparseTiers].sort((a, b) => a - b).join(', ');
    let action;
    if (c.highCount >= 3) {
      const highTiers = c.sparseTiers.filter(t => t <= 3).sort((a, b) => a - b).join(', ');
      action = `Add 1 pair each at tiers ${highTiers}`;
    } else if (c.highCount > 0) {
      const earliestHigh = Math.min(...c.sparseTiers.filter(t => t <= 3));
      action = `Add 1 pair at earliest sparse tier (${earliestHigh})`;
    } else {
      const earliestMed = Math.min(...c.sparseTiers);
      action = `Add 1 pair at tier ${earliestMed}`;
    }
    lines.push(
      `| ${i + 1} | ${c.categoryName} | ${c.groupId} | ${c.label} | ${tiers} | ${c.highCount} | ${c.mediumCount} | ${action} |`
    );
  });
  lines.push('');

  // ── Section 5: Notes for future data PRs ─────────────────────────────────
  lines.push('## 5. Notes for Future Data PRs');
  lines.push('');
  lines.push('- Do not add filler pairs. Each new pair must clearly represent the phoneme contrast.');
  lines.push('- Prefer clean, familiar, contrast-representative word pairs.');
  lines.push('- Human and product review is required before adding pairs to any group.');
  lines.push('- Dataset expansion must be a separate PR from scheduler or UI changes.');
  lines.push('- After adding pairs, re-run `npm run audit:sparse-tiers -- --write` and commit the updated report.');
  lines.push('- After adding pairs, run `npm run validate:data` to confirm no regressions.');
  lines.push('');

  return lines.join('\n');
}

module.exports = { auditSparseTiers, generateMarkdownReport, REPORT_PATH };

// ── CLI entry ─────────────────────────────────────────────────────────────────
if (require.main === module) {
  const { minimalPairs } = loadRepoData();
  const result = auditSparseTiers(minimalPairs);
  const report = generateMarkdownReport(result);

  const writeMode = process.argv.includes('--write');
  if (writeMode) {
    fs.writeFileSync(REPORT_PATH, report, 'utf8');
    console.log(`Report written to ${REPORT_PATH}`);
    console.log(`  ${result.sparseTierCount} single-pair tiers found across ${result.totalGroups} category+group combinations.`);
  } else {
    process.stdout.write(report);
  }
}
